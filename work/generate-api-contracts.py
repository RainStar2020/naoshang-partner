"""Build a reviewable endpoint inventory from the three supplied Markdown documents."""
import json, re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = Path('D:/Backup/Documents/WXWork/1688856411820939/Cache/File/2026-10')
names = ['后端API需求文档.md', '前端API接口清单（功能标注）(1).md', '后端API交接说明（联调须知）.md']
docs = [(name, (source/name).read_text(encoding='utf-8-sig')) for name in names]
entries = {}
for name, text in docs[1:]:
    for line in text.splitlines():
        if not line.startswith('|'): continue
        # An escaped pipe can occur inside the income-export query example.
        cells = re.split(r'(?<!\\)\|', line)[1:-1]
        if len(cells) < 3: continue
        methods = re.findall(r'GET|POST|PATCH|PUT|DELETE', cells[0])
        paths = re.findall(r'`(/[^`]+)`', cells[1])
        for method in methods:
            for path in paths:
                path = path.split('?')[0]
                key = method+' '+path
                if key in entries: continue
                entries[key] = dict(method=method, path=path, description=cells[2].strip(),
                    parameters=cells[-3].strip() if len(cells)>=6 else '文档未提供字段定义，联调前确认',
                    response=cells[-2].strip() if len(cells)>=6 else '文档未提供返回 DTO，联调前确认',
                    source=name, serverOnly=path.startswith('/payments/notify/'))

# Preserve complete requirements paragraphs, including shared-operation conventions.
requirements = docs[0][1]
for entry in entries.values():
    entry['notes'] = '\n'.join(line for line in requirements.splitlines() if '`'+entry['path']+'`' in line)
    entry['pathParams'] = re.findall(r'\{(\w+)\}', entry['path'])
    parts = re.findall(r'[A-Za-z0-9]+', re.sub(r'\{(\w+)\}', r'by-\1', entry['path']))
    entry['name'] = entry['method'].lower()+''.join(p[:1].upper()+p[1:] for p in parts)

out = root/'src/services/contracts'
out.mkdir(parents=True, exist_ok=True)
values = list(entries.values())
(out/'endpoints.js').write_text('// Generated by work/generate-api-contracts.py; document provenance retained.\nexport const endpoints = '+json.dumps(values, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
lines = ["import { callEndpoint } from './client'", '']
for e in values:
    lines += ['/**', ' * '+e['description'], ' * '+e['method']+' '+e['path'],
        ' * 参数：'+e['parameters'], ' * 返回：'+e['response'],
        ' * '+e['notes'].replace('\n','\n * '),
        ' * @param {import("./types").EndpointInput} [input] 路径参数与 query/body 分开传递。',
        ' * @returns {Promise<import("./types").DocumentedResponse>} 具体 DTO 见上方契约；未冻结字段为 unknown。',
        ' */', 'export const '+e['name']+' = (input = {}) => callEndpoint('+json.dumps(e['method']+' '+e['path'])+', input)', '']
(out/'index.js').write_text('\n'.join(lines), encoding='utf-8')
typed = {
    'POST /auth/sessions': ('{ data: LoginRequest }', 'Session'),
    'GET /me/bootstrap': ('EndpointInput', 'Bootstrap'),
    'GET /catalog': ('EndpointInput', '{ categories: Array<{id:string;label:string}>; items: Product[] }'),
    'GET /products/{id}': ('{path:{id:string}}', 'Product'),
    'POST /checkout/quotes': ('{data:CheckoutRequest}', 'CheckoutQuote'),
    'POST /orders': ('{data:{quoteId:string;idempotencyKey:string}}', '{order:Order}'),
    'GET /orders': ('EndpointInput', 'Page<Order>'),
    'GET /orders/{id}': ('{path:{id:string};data?:{contextId?:string}}', '{order:Order;serverTime:string}'),
    'GET /addresses': ('EndpointInput', 'Page<Address>'),
    'GET /members': ('EndpointInput', 'Page<Member>'),
    'POST /payments/attempts': ('{data:{orderId:string;channel:PaymentChannel;idempotencyKey:string}}', 'PaymentAttempt'),
    'GET /payments/attempts/{id}': ('{path:{id:string}}', 'PaymentAttempt'),
    'POST /assets/upload-intents': ('EndpointInput', 'UploadIntent'),
    'GET /jobs/{jobId}': ('{path:{jobId:string}}', 'RenderJob'),
}
decl = ['import type { EndpointInput, DocumentedResponse, LoginRequest, Session, Bootstrap, Product, CheckoutRequest, CheckoutQuote, Order, Page, Address, Member, PaymentChannel, PaymentAttempt, UploadIntent, RenderJob, Result } from "./types"', '']
for e in values:
    args, result = typed.get(e['method']+' '+e['path'], ('EndpointInput', 'DocumentedResponse'))
    optional = '' if e['pathParams'] or e['method'] in ['POST', 'PATCH', 'PUT'] else '?'
    decl += ['/** '+e['description']+' */', f'export function {e["name"]}(input{optional}: {args}): Promise<Result<{result}>>']
(out/'index.d.ts').write_text('\n'.join(decl)+'\n', encoding='utf-8')
print(f'Generated {len(values)} distinct method/path contracts')
